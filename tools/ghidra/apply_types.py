#!/usr/bin/env python3
"""Import gm_types.h into the Ghidra project and apply the arrays.

Why: the field maps live in docs, the decompiler showed raw offsets.  This
script registers the structs generated by ``typegen.py`` in the project's Data
Type Manager and types the three runtime tables at their documented bases:

    0x7ac080  gm_thing[260]       (docs/THING_FIELDS.md §4)
    0x776d60  gm_thing_type[128]  (docs/THING_FIELDS.md §3)
    0x819040  gm_player[8]        (docs/PLAYER_FIELDS.md §1/§3)

It is a pyghidra (JVM) script, not a plain ``mcp.py`` call: the project must be
closed.  Stop the MCP server first:

    tools/ghidra/stop.sh
    tools/ghidra/apply_types.sh --dry-run
    tools/ghidra/apply_types.sh
    tools/ghidra/start.sh

The script is idempotent: an array that is already the right type is skipped.
Existing symbols at documented addresses are re-created as labels after the
range is cleared, so ``ctx.py addr`` and the docs keep resolving.  Nothing is
saved unless every step succeeds.

Evidence is written to ``docs/re/ghidra/types_report.md``: for five hot
functions it records the decompile before/after and how many raw basenames
were replaced by struct fields.
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import socket
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

os.environ.setdefault("JAVA_HOME", os.path.expanduser("~/tools/jdk-21.0.12.1+1"))
os.environ.setdefault("GHIDRA_INSTALL_DIR",
                      os.path.expanduser("~/tools/ghidra_12.1.4_PUBLIC"))

import pyghidra  # noqa: E402

pyghidra.start()

from ghidra.app.util.cparser.C import CParser  # noqa: E402
from ghidra.program.model.data import (ArrayDataType,  # noqa: E402
                                       DataTypeConflictHandler)
from ghidra.program.model.address import AddressSet  # noqa: E402
from ghidra.program.model.symbol import SourceType  # noqa: E402
from ghidra.util.task import ConsoleTaskMonitor  # noqa: E402

DEFAULT_PROJECT = os.path.join(ROOT, "re", "ghidra")
DEFAULT_NAME = "gunmetal"
DEFAULT_PROGRAM = "/gundx.exe-902b77"
DEFAULT_HEADER = os.path.join(ROOT, "tools", "ghidra", "gm_types.h")
REPORT = os.path.join(ROOT, "docs", "re", "ghidra", "types_report.md")

ARRAYS = (
    ("gm_thing", 260, 0x7AC080, "things"),
    ("gm_thing_type", 128, 0x776D60, "thing_types"),
    ("gm_player", 8, 0x819040, "players"),
)


def port_open(port: int = 8765) -> bool:
    with socket.socket() as sock:
        sock.settimeout(0.2)
        return sock.connect_ex(("127.0.0.1", port)) == 0


def documented_addresses() -> set[int]:
    """Addresses mentioned in docs/NOTES, used to keep useful labels."""
    out: set[int] = set()
    paths = (glob.glob(os.path.join(ROOT, "docs", "**", "*.md"), recursive=True)
             + [os.path.join(ROOT, "NOTES.md")])
    for path in paths:
        try:
            text = open(path, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        for raw in re.findall(r"\b0x[0-9a-fA-F]{6,8}\b", text):
            out.add(int(raw, 16))
    return out


def decompile_all(program, addresses: list[int]) -> dict[int, str]:
    """Decompile sample functions with a fresh interface (no stale cache)."""
    from ghidra.app.decompiler import DecompInterface
    interface = DecompInterface()
    interface.openProgram(program)
    monitor = ConsoleTaskMonitor()
    out = {}
    space = program.getAddressFactory().getDefaultAddressSpace()
    for va in addresses:
        func = program.getFunctionManager().getFunctionAt(space.getAddress(va))
        if func is None:
            out[va] = "(no function)"
            continue
        result = interface.decompileFunction(func, 120, monitor)
        out[va] = (result.getDecompiledFunction().getC()
                   if result and result.getDecompiledFunction() else "(failed)")
    interface.dispose()
    return out


FIELD_RE = re.compile(
    r"\.(?:health|max_health|movement_type|shields|weapon_id|"
    r"collision_radius|speed|pose|trail_pos|object|sector|flags_a|"
    r"flags_b|flags_c|expire_ticks|timeout_timer|child_count)\b")


def metrics(code: str) -> dict:
    return {
        # base+offset style references that the struct should replace
        "raw_bases": len(re.findall(
            r"&?DAT_00(?:7ac|81b|81c)[0-9a-f]+", code)),
        "arrays": len(re.findall(
            r"(?:things|players|thing_types|gm_thing_ARRAY|gm_player_ARRAY|"
            r"gm_thing_type_ARRAY)\[", code)),
        "named_fields": len(FIELD_RE.findall(code)),
    }


def rename_primary(symtab, addr, name: str) -> None:
    """Give the array a short semantic name (``things``, ``players``)."""
    try:
        for sym in symtab.getSymbols(addr):
            if sym.isPrimary():
                if sym.getName() != name:
                    sym.setName(name, SourceType.USER_DEFINED)
                return
        symtab.createLabel(addr, name, SourceType.USER_DEFINED)
    except Exception as exc:  # naming is cosmetic; typing already succeeded
        print(f"apply_types: rename {name}@{addr}: {exc}", file=sys.stderr)


def split_header(text: str) -> list[str]:
    """One chunk per typedef struct, so CParser returns every type."""
    chunks = re.split(r"(?=typedef struct)", text)
    return [chunk for chunk in chunks if "typedef struct" in chunk]


def write_report(before: dict[int, str], after: dict[int, str]) -> None:
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    lines = [
        "# Struct types applied to the Ghidra project",
        "",
        "Generated by `tools/ghidra/apply_types.py` from `tools/ghidra/gm_types.h`.",
        "The types come from `docs/THING_FIELDS.md` §3/§4 and",
        "`docs/PLAYER_FIELDS.md` §3; pseudo-C remains a hypothesis.",
        "",
        "| function | `&DAT_` refs before | after | array refs after | named field refs after |",
        "|---|---:|---:|---:|---:|",
    ]
    for va in sorted(before):
        b, a = metrics(before[va]), metrics(after.get(va, ""))
        lines.append(f"| `{va:#x}` | {b['raw_bases']} | {a['raw_bases']} | "
                     f"{a['arrays']} | {a['named_fields']} |")
    lines += ["", "## Sample after", ""]
    for va in sorted(after):
        sample = [line.strip() for line in after[va].splitlines()
                  if re.search(r"(?:things|players|thing_types)\[|"
                               r"gm_(?:thing|player)", line)]
        lines.append(f"### `{va:#x}`")
        lines.append("")
        lines.extend(f"    {line[:180]}" for line in sample[:4])
        lines.append("")
    with open(REPORT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"apply_types: report -> {REPORT}")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--project-path", default=DEFAULT_PROJECT)
    ap.add_argument("--project-name", default=DEFAULT_NAME)
    ap.add_argument("--program", default=DEFAULT_PROGRAM)
    ap.add_argument("--header", default=DEFAULT_HEADER)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-report", dest="report", action="store_false")
    ap.add_argument("--allow-server", action="store_true",
                    help="open a copy while the real server still runs")
    opts = ap.parse_args(argv)

    if (port_open() and not opts.allow_server
            and os.path.abspath(opts.project_path)
            == os.path.abspath(DEFAULT_PROJECT)):
        print("apply_types: the MCP server is running and holds the project; "
              "run tools/ghidra/stop.sh first (or --allow-server for a copy)",
              file=sys.stderr)
        return 2

    header = open(opts.header, encoding="utf-8").read()
    chunks = split_header(header)
    if len(chunks) != len(ARRAYS):
        print(f"apply_types: expected {len(ARRAYS)} structs in "
              f"{opts.header}, found {len(chunks)}", file=sys.stderr)
        return 2

    docs = documented_addresses()
    samples = [0x470C70, 0x470500, 0x4752D0, 0x443690, 0x47A980]
    project = pyghidra.open_project(opts.project_path, opts.project_name,
                                    create=False)
    with pyghidra.program_context(project, opts.program) as program:
        before = decompile_all(program, samples)
        dtm = program.getDataTypeManager()
        listing = program.getListing()
        symtab = program.getSymbolTable()
        space = program.getAddressFactory().getDefaultAddressSpace()
        monitor = ConsoleTaskMonitor()

        planned = []
        for name, count, base, symbol in ARRAYS:
            dt = dtm.getDataType("/" + name)
            planned.append((name, count, base, symbol, dt))
        for name, count, base, symbol, dt in planned:
            print(f"apply_types: {name}[{count}] @ {base:#x}: "
                  + ("exists" if dt else "new"),
                  file=sys.stderr)
        if opts.dry_run:
            print("apply_types: dry run, nothing saved", file=sys.stderr)
            return 0

        with pyghidra.transaction(program, "gm_types"):
            for chunk in chunks:
                parser = CParser(dtm)
                parsed = parser.parse(chunk)
                if not parser.didParseSucceed() or parsed is None:
                    print(f"apply_types: parse failed: {parser.getParseMessages()}",
                          file=sys.stderr)
                    return 2
                name = parsed.getName()
                existing = dtm.getDataType("/" + name)
                if existing is None:
                    dtm.addDataType(parsed, DataTypeConflictHandler.DEFAULT_HANDLER)
                elif existing.getLength() != parsed.getLength():
                    print(f"apply_types: {name} exists with length "
                          f"{existing.getLength()}, docs say "
                          f"{parsed.getLength()}; aborting (remove the old "
                          f"array/type by hand first)", file=sys.stderr)
                    return 2
                else:
                    # Same size, but a field may have been renamed: replace the
                    # definition in place so existing data picks it up.
                    dtm.addDataType(parsed, DataTypeConflictHandler.REPLACE_HANDLER)

        for name, count, base, symbol in ARRAYS:
            dt = dtm.getDataType("/" + name)
            arr = ArrayDataType(dt, count, dt.getLength(), dtm)
            addr = space.getAddress(base)
            end = addr.add(arr.getLength() - 1)
            current = listing.getDataAt(addr)
            if (current is not None
                    and current.getDataType().getName() == arr.getName()):
                with pyghidra.transaction(program, f"rename {symbol}"):
                    rename_primary(symtab, addr, symbol)
                print(f"apply_types: {name}[{count}] already applied",
                      file=sys.stderr)
                continue
            funcs = list(program.getFunctionManager().getFunctions(
                AddressSet(addr, end), True))
            if funcs:
                print(f"apply_types: refusing to clear code in {name} range "
                      f"({len(funcs)} functions, first {funcs[0]})",
                      file=sys.stderr)
                return 2
            preserve = []
            for sym in symtab.getAllSymbols(True):
                off = sym.getAddress().getOffset()
                if base <= off <= base + arr.getLength() - 1:
                    if off in docs or sym.getSource() == SourceType.USER_DEFINED:
                        preserve.append((off, sym.getName()))
            with pyghidra.transaction(program, f"apply {name}"):
                listing.clearCodeUnits(addr, end, False)
                listing.createData(addr, arr)
                for off, sym_name in preserve:
                    try:
                        symtab.createLabel(space.getAddress(off), sym_name,
                                           SourceType.USER_DEFINED)
                    except Exception as exc:  # label clash is not fatal
                        print(f"apply_types: label {sym_name}@{off:#x}: {exc}",
                              file=sys.stderr)
                rename_primary(symtab, addr, symbol)
            print(f"apply_types: applied {name}[{count}] @ {base:#x}; "
                  f"{len(preserve)} labels restored", file=sys.stderr)

        program.save("apply_types: gm structs", monitor)

        # Every cached pseudo-C that touches these tables is now outdated.
        try:
            sys.path.insert(0, os.path.join(ROOT, "tools", "ghidra"))
            import fncache
            directory = fncache.cache_dir(
                fncache.exe_sha(fncache.find_exe()))
            dropped = fncache.invalidate_all(directory)
            print(f"apply_types: cache invalidated ({dropped} entries); "
                  f"warm it with fncache.py warm --names/--file", file=sys.stderr)
        except Exception as exc:
            print(f"apply_types: cache invalidation skipped: {exc}",
                  file=sys.stderr)

        after = decompile_all(program, samples)
        if opts.report:
            write_report(before, after)
        for va in samples:
            b, a = metrics(before[va]), metrics(after[va])
            print(f"apply_types: {va:#x}: raw bases {b['raw_bases']} -> "
                  f"{a['raw_bases']}, named fields {a['named_fields']}",
                  file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
