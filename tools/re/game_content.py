#!/usr/bin/env python3
"""Content-addressed identities for the shipped level/geometry files (M0.8).

The tests name levels the way the *manifest* does.  If an installation has
files renamed or swapped (this one does: `level1.sbt` holds the bytes that
belong to `level2.sbt` and vice versa, per
`docs/manifests/gunmetal-3dfx-136.sha256`), a name-based test silently checks
the wrong content.  This tool records the FNV-1a64 of the canonical content of
every shipped `.sbt`/`.sbw` (looked up by SHA-256 in the manifest) and prints a
C++ header; the tests resolve a file by content, so names stop mattering.

    python3 tools/re/game_content.py --check     # report anomalies only
    python3 tools/re/game_content.py --write     # regenerate the header
    python3 tools/re/game_content.py --json

Generator inputs (read-only): the installation (or `--game`) and
`docs/manifests/gunmetal-3dfx-136.sha256`.  Output:
`engine/tests/game_content.h`.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_GAME = "/mnt/d/games/Gunmetal 3dfx"
MANIFEST = os.path.join(ROOT, "docs", "manifests", "gunmetal-3dfx-136.sha256")
HEADER = os.path.join(ROOT, "engine", "tests", "game_content.h")
EXTS = (".sbt", ".sbw")

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
FNV_MASK = (1 << 64) - 1


def fnv1a64(data: bytes, seed: int = FNV_OFFSET) -> int:
    value = seed
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & FNV_MASK
    return value


def manifest_names() -> dict[str, str]:
    """``sha256 -> canonical relative path`` for the extensions we track."""
    out: dict[str, str] = {}
    with open(MANIFEST, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            digest, _, name = line.partition("  ")
            if name.lower().endswith(EXTS):
                out[digest] = name
    return out


def index_game(game: str) -> list[tuple[str, str, str]]:
    """``[(rel, sha256, fnv)]`` for every tracked file in *game* (one read)."""
    rows = []
    for cur, dirs, files in os.walk(game):
        dirs[:] = sorted(d for d in dirs if d.upper() != "SAVEGAME")
        for name in sorted(files):
            if name.lower().endswith(EXTS):
                path = os.path.join(cur, name)
                with open(path, "rb") as fh:
                    blob = fh.read()
                rel = os.path.relpath(path, game).replace(os.sep, "/")
                rows.append((rel, hashlib.sha256(blob).hexdigest(),
                             fnv1a64(blob)))
    return rows


def build(game: str) -> tuple[list[dict], list[dict]]:
    """Return ``(content, anomalies)``.

    ``content``: ``[{"name", "fnv", "actual"}]`` in canonical name order, where
    ``actual`` is the file in *game* whose bytes hash to the canonical digest.
    ``anomalies``: files whose current name differs from the manifest name.
    """
    canonical = manifest_names()          # sha -> name
    by_sha: dict[str, tuple[str, int]] = {}
    for rel, digest, fnv in index_game(game):
        by_sha.setdefault(digest, (rel, fnv))
    rows = []
    anomalies = []
    for digest, name in sorted(canonical.items(), key=lambda kv: kv[1]):
        hit = by_sha.get(digest)
        if hit is None:
            continue
        rel, fnv = hit
        rows.append({"name": name, "fnv": fnv, "actual": rel})
        if rel != name:
            anomalies.append({"canonical": name, "actual": rel})
    return rows, anomalies


def render_header(rows: list[dict]) -> str:
    lines = [
        "// Generated by tools/re/game_content.py --write; do not edit.",
        "// FNV-1a64 of the *canonical* content of each shipped level file",
        "// (looked up by SHA-256 in docs/manifests/gunmetal-3dfx-136.sha256).",
        "// Tests resolve a file by this hash, so a renamed or swapped file in",
        "// an installation cannot silently change what is being checked.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace gmtest {",
        "",
        "struct GameContent {",
        "    const char* name;",
        "    std::uint64_t fnv;",
        "};",
        "",
        "inline constexpr GameContent kGameContent[] = {",
    ]
    for row in rows:
        lines.append('    {"%s", 0x%016xull},' % (row["name"], row["fnv"]))
    lines += [
        "};",
        "",
        "inline constexpr std::size_t kGameContentCount =",
        "    sizeof(kGameContent) / sizeof(kGameContent[0]);",
        "",
        "} // namespace gmtest",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game", default=os.environ.get("GUNMETAL_GAME",
                                                     DEFAULT_GAME))
    ap.add_argument("--check", action="store_true",
                    help="only report files whose name differs from the manifest")
    ap.add_argument("--write", action="store_true", help="write the C++ header")
    ap.add_argument("--json", action="store_true")
    opts = ap.parse_args(argv)

    rows, anomalies = build(opts.game)
    if opts.json:
        print(json.dumps({"files": len(rows), "anomalies": anomalies,
                          "content": rows}, indent=2, ensure_ascii=False))
        return 0 if rows else 1
    for item in anomalies:
        print("name/content mismatch: %-14s holds %s"
              % (item["canonical"], item["actual"]))
    print("%d files, %d anomalies" % (len(rows), len(anomalies)))
    if opts.write:
        text = render_header(rows)
        tmp = HEADER + ".tmp"
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, HEADER)
        print("wrote %s" % os.path.relpath(HEADER, ROOT))
    return 0 if rows else 1


if __name__ == "__main__":
    raise SystemExit(main())
