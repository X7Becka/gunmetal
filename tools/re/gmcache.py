#!/usr/bin/env python3
"""Persistent cache for reverse-engineering artefacts (fast, survives reboot).

Why this exists
---------------
``/tmp`` in this WSL install is tmpfs: ``wsl --shutdown`` (and any reboot)
erased the objdump listing and the local ``gundx.exe`` copy, so every RE tool
and half of ``regress.py`` failed until they were regenerated by hand.  A game
mirror on ``/dev/sdd`` also removes the drvfs (``/mnt/d``, 9p) latency from the
test loop: ``gm.py sob --check`` went from 1.5 s to 0.07 s, the inventory walk
from 7.6 s to ~0.5 s.

Layout (``GUNMETAL_CACHE`` overrides the root, default ``~/.cache/gunmetal-re``)::

    gundx.asm            objdump -D -M intel listing (built on demand)
    gundx.asm.idx        binary index: vma + line offset, see tools/re/exelib.py
    gundx.exe            copy of the shipped executable (provenance, offline runs)
    game/                read-only mirror of the installation
    game.manifest.json   size/mtime/sha256 of every mirrored file

Nothing here writes to the installation.  The mirror is a cache: if it drifts
from the install, ``sync`` (or ``regress.py --mirror``) refreshes it, so a
stale copy can never silently stand in for the real data.

    python3 tools/re/gmcache.py status
    python3 tools/re/gmcache.py build            # listing + index + exe copy
    python3 tools/re/gmcache.py mirror --sync    # create/refresh the mirror
    python3 tools/re/gmcache.py mirror --check   # fast stat comparison
    python3 tools/re/gmcache.py mirror --verify  # sha256 of every file
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import exelib  # noqa: E402

CACHE = exelib.cache_dir()
MIRROR = os.path.join(CACHE, "game")
MANIFEST = os.path.join(CACHE, "game.manifest.json")
MANIFEST_VERSION = 1


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _scan(root: str) -> dict[str, list]:
    """``rel -> [size, mtime_ns]`` for every regular file under *root*."""
    out: dict[str, list] = {}
    for base, dirs, files in os.walk(root):
        dirs.sort()
        for name in sorted(files):
            path = os.path.join(base, name)
            try:
                st = os.stat(path)
            except OSError:
                continue
            if os.path.isfile(path):
                rel = os.path.relpath(path, root).replace(os.sep, "/")
                out[rel] = [st.st_size, st.st_mtime_ns]
    return out


def load_manifest() -> dict:
    try:
        with open(MANIFEST, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}
    if data.get("version") != MANIFEST_VERSION:
        return {}
    return data


def _save_manifest(data: dict) -> None:
    os.makedirs(CACHE, exist_ok=True)
    tmp = MANIFEST + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, ensure_ascii=False, sort_keys=True)
    os.replace(tmp, MANIFEST)


def _same(src: str, dst: str, entry: list) -> bool:
    """Cheap identity test: destination size/mtime equals the recorded entry."""
    try:
        st = os.stat(dst)
    except OSError:
        return False
    return st.st_size == entry[0] and st.st_mtime_ns == entry[1]


def sync(install: str, deep: bool = False, verbose: bool = True) -> dict:
    """Copy *install* to the mirror, refreshing only files that changed.

    Returns ``{"files", "copied", "removed", "bytes", "sha256", "seconds"}``.
    """
    t0 = time.time()
    src = _scan(install)
    old = load_manifest()
    old_files: dict = old.get("files", {})
    files: dict[str, list] = {}
    copied = removed = 0
    total_bytes = 0
    os.makedirs(MIRROR, exist_ok=True)
    for rel, (size, mtime) in src.items():
        s = os.path.join(install, rel)
        d = os.path.join(MIRROR, rel)
        prev = old_files.get(rel)
        fresh = (isinstance(prev, list) and prev[:2] == [size, mtime]
                 and os.path.exists(d))
        if fresh and not deep:
            files[rel] = prev
            total_bytes += size
            continue
        os.makedirs(os.path.dirname(d) or MIRROR, exist_ok=True)
        shutil.copy2(s, d)          # keeps mtime, so the cache survives a restart
        digest = _sha256(d)
        files[rel] = [size, mtime, digest]
        copied += 1
        total_bytes += size
        if verbose and copied % 500 == 0:
            print("  mirrored %d files ..." % copied, file=sys.stderr)
    # Drop files that no longer exist in the installation.
    for rel in list(old_files):
        if rel not in src:
            d = os.path.join(MIRROR, rel)
            if os.path.exists(d):
                os.unlink(d)
            removed += 1
    state = {"version": MANIFEST_VERSION, "install": os.path.abspath(install),
             "files": files}
    _save_manifest(state)
    digest = hashlib.sha256()
    for rel in sorted(files):
        digest.update(b"%s %s\n" % (files[rel][2].encode(), rel.encode()))
    return {"files": len(files), "copied": copied, "removed": removed,
            "bytes": total_bytes, "sha256": digest.hexdigest(),
            "seconds": time.time() - t0}


def check(install: str, deep: bool = False) -> dict:
    """Compare install and mirror.  ``deep`` re-hashes both sides."""
    src = _scan(install)
    data = load_manifest()
    files = data.get("files", {})
    mirror = _scan(MIRROR) if os.path.isdir(MIRROR) else {}
    missing = sorted(set(src) - set(mirror))
    extra = sorted(set(mirror) - set(src))
    stale: list[str] = []
    for rel, (size, mtime) in src.items():
        if rel in missing:
            continue
        if mirror[rel] != [size, mtime]:
            stale.append(rel)
            continue
        entry = files.get(rel)
        if deep and (not isinstance(entry, list) or entry[:2] != [size, mtime]
                     or entry[2] != _sha256(os.path.join(MIRROR, rel))):
            stale.append(rel)
    return {"install": os.path.abspath(install), "source_files": len(src),
            "mirror_files": len(mirror), "missing": missing, "extra": extra,
            "stale": stale, "deep": deep,
            "ok": not missing and not extra and not stale}


def ensure_mirror(install: str, force: bool = False,
                  ttl: float | None = None) -> str:
    """Sync when the mirror is missing or drifted; return its path.

    ``check()`` costs ~7 s on this box (4215 stats over drvfs), which would
    eat the win the mirror provides.  A successful check is therefore cached
    in ``mirror.ok`` for ``ttl`` seconds (default ``GUNMETAL_MIRROR_TTL`` or
    900): the mirror is only re-validated every 15 minutes, or immediately
    when ``force``/``--verify-mirror`` is passed.  Any change to the manifest
    invalidates the stamp by mtime, so a sync always triggers a fresh check.
    """
    if ttl is None:
        ttl = float(os.environ.get("GUNMETAL_MIRROR_TTL", "900"))
    stamp = os.path.join(CACHE, "mirror.ok")
    exe_path = os.path.join(install, os.path.basename(exelib.EXE))
    try:
        install_stamp = os.stat(exe_path).st_mtime_ns
    except OSError:
        install_stamp = 0
    if not force and os.path.isdir(MIRROR) and os.path.exists(stamp):
        try:
            with open(stamp, "r", encoding="utf-8") as fh:
                cached = json.load(fh)
            if (time.time() - cached.get("checked", 0) < ttl
                    and cached.get("install") == os.path.abspath(install)
                    and cached.get("exe_mtime_ns") == install_stamp
                    and cached.get("manifest_mtime_ns")
                    == os.stat(MANIFEST).st_mtime_ns):
                return MIRROR
        except (OSError, ValueError):
            pass
    state = check(install)
    if force or not state["ok"]:
        why = ("missing mirror" if not os.path.isdir(MIRROR) else
               "drift: %d missing, %d extra, %d stale"
               % (len(state["missing"]), len(state["extra"]), len(state["stale"])))
        print("gmcache: %s -> syncing %s" % (why, MIRROR), file=sys.stderr)
        sync(install)
    try:
        manifest_mtime = os.stat(MANIFEST).st_mtime_ns
    except OSError:
        manifest_mtime = 0
    try:
        with open(stamp, "w", encoding="utf-8") as fh:
            json.dump({"checked": time.time(), "install": os.path.abspath(install),
                       "exe_mtime_ns": install_stamp,
                       "manifest_mtime_ns": manifest_mtime}, fh)
    except OSError:
        pass
    return MIRROR


def build(install: str | None = None) -> dict:
    """Listing + index (via exelib) and an exe copy in the cache."""
    os.makedirs(CACHE, exist_ok=True)
    info = exelib.listing_info()
    exe_copy = exelib.cache_path("gundx.exe")
    src_exe = install or exelib.EXE
    if os.path.isdir(src_exe):
        src_exe = os.path.join(src_exe, os.path.basename(exelib.EXE))
    copied = False
    if os.path.isfile(src_exe):
        if (not os.path.exists(exe_copy)
                or os.path.getsize(exe_copy) != os.path.getsize(src_exe)):
            shutil.copy2(src_exe, exe_copy)
            copied = True
    info.update({"cache": CACHE, "exe_copy": exe_copy,
                 "exe_copy_fresh": copied, "exe_sha256": exelib.exe_sha256()})
    return info


def cmd_status(opts) -> int:
    data = load_manifest()
    mirror_files = len(_scan(MIRROR)) if os.path.isdir(MIRROR) else 0
    exe_copy = exelib.cache_path("gundx.exe")
    listing = exelib.asm_path()
    idx = listing + ".idx"
    payload = {
        "cache": CACHE,
        "install": exelib.EXE,
        "install_sha256": exelib.exe_sha256(),
        "exe_copy": os.path.exists(exe_copy),
        "listing": listing,
        "listing_bytes": os.path.getsize(listing) if os.path.exists(listing) else 0,
        "index": os.path.exists(idx),
        "mirror": MIRROR,
        "mirror_files": mirror_files,
        "manifest_files": len(data.get("files", {})),
        "manifest_install": data.get("install"),
    }
    if opts.json:
        print(json.dumps(payload, indent=2, ensure_ascii=False))
        return 0
    print("cache    : %s" % payload["cache"])
    print("exe      : %s (sha256 %s)" % (payload["install"],
                                         payload["install_sha256"]))
    print("exe copy : %s" % ("yes" if payload["exe_copy"] else "no"))
    print("listing  : %s (%d bytes, index %s)"
          % (payload["listing"], payload["listing_bytes"],
             "yes" if payload["index"] else "no"))
    print("mirror   : %s (%d files, manifest %d)"
          % (payload["mirror"], payload["mirror_files"],
             payload["manifest_files"]))
    if not os.path.isdir(MIRROR):
        print("           not created; run: gmcache.py mirror --sync")
    return 0


def cmd_build(opts) -> int:
    info = build(opts.game)
    print("gmcache: %d listing lines, index %s, exe copy %s"
          % (info["lines"], info["index"], info["exe_copy"]))
    return 0


def cmd_mirror(opts) -> int:
    if opts.sync:
        stats = sync(opts.game)
        print("mirror %s: %d files, %d copied, %d removed, %.1f MiB, %.2fs"
              % (MIRROR, stats["files"], stats["copied"], stats["removed"],
                 stats["bytes"] / 1048576, stats["seconds"]))
        print("digest %s" % stats["sha256"])
        return 0
    state = check(opts.game, deep=opts.verify)
    if opts.json:
        print(json.dumps({k: v for k, v in state.items() if k != "missing"
                          and k != "extra" and k != "stale"}, indent=2))
        return 0 if state["ok"] else 1
    if state["ok"]:
        print("mirror ok: %d files%s" % (state["source_files"],
                                         " (sha256 verified)" if opts.verify else ""))
        return 0
    print("mirror drifted: %d missing, %d extra, %d stale"
          % (len(state["missing"]), len(state["extra"]), len(state["stale"])))
    for rel in (state["missing"] + state["extra"] + state["stale"])[:10]:
        print("  %s" % rel)
    print("run: python3 tools/re/gmcache.py mirror --sync")
    return 1


def cmd_selftest(opts) -> int:
    """Prove the listing index matches a direct scan (bisect + seek)."""
    info = exelib.listing_info()
    vmas, offs, path = exelib.asm_index()
    path = exelib.asm_path()
    with open(path, "rb") as fh:
        blob = fh.read()
    step = max(1, len(vmas) // 97)
    sample = list(range(0, len(vmas), step))
    bad = 0
    for i in sample:
        lo = blob[offs[i]:].split(b"\n", 1)[0].decode("latin1")
        got = exelib.disasm(vmas[i], lines=1)
        if not got or got[0] != lo:
            bad += 1
            if bad <= 5:
                print("  mismatch at line %d vma 0x%x:\n    idx: %r\n    raw: %r"
                      % (i, vmas[i], got[:1], lo))
    for i in sample[:20]:
        nxt = vmas[i + 1] if i + 1 < len(vmas) else vmas[i] + 1
        rng = exelib.disasm(vmas[i], nxt)
        if not rng or rng[0] != blob[offs[i]:].split(b"\n", 1)[0].decode("latin1"):
            bad += 1
    print("selftest: %d sampled rows, %d range starts, %d mismatches (%d lines)"
          % (len(sample), min(20, len(sample)), bad, info["lines"]))
    return 0 if bad == 0 else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game", default=os.environ.get("GUNMETAL_GAME",
                                                     os.path.dirname(exelib.EXE)),
                    help="Gunmetal installation (default: %(default)s)")
    sub = ap.add_subparsers(dest="cmd")

    p = sub.add_parser("status", help="cache contents and exe provenance")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("build", help="build the listing, its index and the exe copy")
    p.set_defaults(func=cmd_build)

    p = sub.add_parser("selftest", help="verify the listing index against raw rows")
    p.set_defaults(func=cmd_selftest)

    p = sub.add_parser("mirror", help="local mirror of the installation")
    p.add_argument("--sync", action="store_true", help="create/refresh the mirror")
    p.add_argument("--check", action="store_true", help="compare by size+mtime (default)")
    p.add_argument("--verify", action="store_true", help="re-hash every file")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_mirror)

    opts = ap.parse_args(argv)
    if not opts.cmd:
        ap.print_help()
        return 2
    return opts.func(opts)


if __name__ == "__main__":
    raise SystemExit(main())
