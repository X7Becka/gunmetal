#!/usr/bin/env python3
"""Regenerate ``gm/_sou1_tables.py`` from ``gundx.exe``.

SOU1's step table, 32 volume-row pointers and the shared 0x1d80-byte delta
curve are data in the shipped executable (``0x850480``/``0x850500``/
``0x850540``).  ``tools/re/sou1_model.py`` reads them through ``exelib`` and has
been verified against the real decoder on all 983 entries; this tool freezes
the same bytes into the stdlib-only package.

    python3 tools/gen_sou1_tables.py           # rewrite gm/_sou1_tables.py
    python3 tools/gen_sou1_tables.py --check   # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "re"))
sys.path.insert(0, str(ROOT))

import sou1_model  # noqa: E402

OUT = ROOT / "gm" / "_sou1_tables.py"


def render() -> str:
    step = ", ".join(str(v) for v in sou1_model.STEP)
    bases = ", ".join(str((p - sou1_model.DELTA_BASE) // 4)
                      for p in sou1_model.VOLUME_PTRS)
    lines = []
    curve = sou1_model.CURVE
    for i in range(0, len(curve), 16):
        lines.append("    " + ", ".join(str(v) for v in curve[i:i + 16]) + ",")
    return f'''"""SOU1 decoder tables, extracted from gundx.exe.

Generated by ``tools/gen_sou1_tables.py``; do not edit by hand.

* ``STEP`` -- ``0x850500``, the 16 nibble adaptation steps.
* ``VOLUME_BASE`` -- ``0x850480``, 32 row offsets (in dwords) into ``CURVE``.
* ``CURVE`` -- ``0x850540..0x8522c0``, the shared signed dword delta curve.
"""

STEP = ({step})

VOLUME_BASE = ({bases})

CURVE = (
{chr(10).join(lines)}
)
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    opts = ap.parse_args(argv)
    text = render()
    if opts.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("gm/_sou1_tables.py is out of date", file=sys.stderr)
            return 1
        print("sou1 tables ok")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(sou1_model.CURVE)} curve dwords)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
